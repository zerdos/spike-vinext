import { describe, it, expect, beforeEach } from "vitest";
import {
  resetInMemoryUsersState,
  findUserByIdentifier,
  createUserApiToken,
  revokeUserApiToken,
  updateUserProviderTokens,
  verifyApiToken,
  findApiTokenByValue,
  ADMIN_DEFAULT_API_TOKEN,
} from "@/lib/auth/users-db";
import {
  getSessionFromRequest,
  verifyBearerAuth,
  getBearerTokenFromRequest,
} from "@/lib/auth/session";
import {
  getClientBearerToken,
  setClientBearerToken,
  clearClientBearerToken,
  authenticatedFetch,
} from "@/lib/auth/client-token";
import { GET as getTokens, POST as postTokens, DELETE as deleteTokens } from "@/app/api/settings/tokens/route";
import { POST as changePasswordPost } from "@/app/api/settings/password/route";
import { GET as getSession } from "@/app/api/auth/session/route";
import { GET as getHello } from "@/app/api/hello/route";
import { POST as mcpPost } from "@/app/api/mcp/route";
import { POST as virtualGatewayPost } from "@/app/api/mcp/g/[gatewaySlug]/route";
import { POST as ssePost } from "@/app/api/mcp/sse/route";

describe("Bearer Token Protection for API Calls (Settings-Configured Tokens)", () => {
  beforeEach(async () => {
    await resetInMemoryUsersState();
    clearClientBearerToken();
  });

  describe("lib/auth/users-db: verifyApiToken", () => {
    it("authenticates the default admin master token configured for Spike Land", async () => {
      const result = await verifyApiToken(ADMIN_DEFAULT_API_TOKEN);
      expect(result).not.toBeNull();
      expect(result?.user.email).toBe("admin@spike.land");
      expect(result?.user.role).toBe("admin");
      expect(result?.tokenRecord?.tokenValue).toBe(ADMIN_DEFAULT_API_TOKEN);
    });

    it("authenticates personal MCP tokens generated by users in settings and updates last_used_at", async () => {
      const admin = await findUserByIdentifier("admin@spike.land");
      expect(admin).not.toBeNull();

      const created = await createUserApiToken(admin!.id, {
        name: "Cursor Laptop Key",
        customTokenValue: "spk_live_cursor_abc123xyz789",
      });

      expect(created.tokenValue).toBe("spk_live_cursor_abc123xyz789");

      const authResult = await verifyApiToken("spk_live_cursor_abc123xyz789");
      expect(authResult).not.toBeNull();
      expect(authResult?.user.id).toBe(admin!.id);
      expect(authResult?.tokenRecord?.id).toBe(created.id);
      expect(authResult?.tokenRecord?.lastUsedAt).toBeTruthy();
    });

    it("rejects revoked API tokens immediately", async () => {
      const admin = await findUserByIdentifier("admin@spike.land");
      const created = await createUserApiToken(admin!.id, {
        name: "Temporary Test Token",
        customTokenValue: "spk_live_temp_to_be_revoked_456",
      });

      expect(await verifyApiToken("spk_live_temp_to_be_revoked_456")).not.toBeNull();

      const revoked = await revokeUserApiToken(admin!.id, created.id);
      expect(revoked).toBe(true);

      const afterRevoke = await verifyApiToken("spk_live_temp_to_be_revoked_456");
      expect(afterRevoke).toBeNull();
    });

    it("authenticates SPIKE_API_KEY configured in upstream provider tokens", async () => {
      const admin = await findUserByIdentifier("admin@spike.land");
      await updateUserProviderTokens(admin!.id, {
        SPIKE_API_KEY: "spk_live_custom_provider_key_999",
      });

      const verified = await verifyApiToken("spk_live_custom_provider_key_999");
      expect(verified).not.toBeNull();
      expect(verified?.user.id).toBe(admin!.id);
    });

    it("rejects unknown, empty, or whitespace tokens", async () => {
      expect(await verifyApiToken("")).toBeNull();
      expect(await verifyApiToken("   ")).toBeNull();
      expect(await verifyApiToken("spk_live_completely_bogus_token")).toBeNull();
    });
  });

  describe("lib/auth/session: verifyBearerAuth and getSessionFromRequest", () => {
    it("extracts bearer token from request headers", () => {
      const req = new Request("https://spike.land/api/mcp", {
        headers: { Authorization: "Bearer spk_live_test_header_val" },
      });
      expect(getBearerTokenFromRequest(req)).toBe("spk_live_test_header_val");

      const reqNoAuth = new Request("https://spike.land/api/mcp");
      expect(getBearerTokenFromRequest(reqNoAuth)).toBeNull();
    });

    it("authenticates getSessionFromRequest using Bearer token configured in settings", async () => {
      const req = new Request("https://spike.land/api/settings/tokens", {
        headers: { Authorization: `Bearer ${ADMIN_DEFAULT_API_TOKEN}` },
      });

      const session = await getSessionFromRequest(req);
      expect(session).not.toBeNull();
      expect(session?.user.email).toBe("admin@spike.land");
      expect(session?.user.role).toBe("admin");
    });

    it("verifyBearerAuth returns detailed auth result for valid and invalid bearer tokens", async () => {
      const validReq = new Request("https://spike.land/api/mcp", {
        headers: { Authorization: `Bearer ${ADMIN_DEFAULT_API_TOKEN}` },
      });
      const validAuth = await verifyBearerAuth(validReq);
      expect(validAuth.authenticated).toBe(true);
      expect(validAuth.user?.email).toBe("admin@spike.land");

      const invalidReq = new Request("https://spike.land/api/mcp", {
        headers: { Authorization: "Bearer spk_live_invalid_garbage" },
      });
      const invalidAuth = await verifyBearerAuth(invalidReq);
      expect(invalidAuth.authenticated).toBe(false);
      expect(invalidAuth.error).toBe("invalid_bearer_token");

      const missingReq = new Request("https://spike.land/api/mcp");
      const missingAuth = await verifyBearerAuth(missingReq);
      expect(missingAuth.authenticated).toBe(false);
      expect(missingAuth.error).toBe("missing_bearer_token");
    });
  });

  describe("Protected /api/settings endpoints with Bearer Token", () => {
    it("allows GET /api/settings/tokens with Bearer token configured in settings", async () => {
      const req = new Request("https://spike.land/api/settings/tokens", {
        headers: { Authorization: `Bearer ${ADMIN_DEFAULT_API_TOKEN}` },
      });

      const res = await getTokens(req);
      expect(res.status).toBe(200);
      const data = (await res.json()) as { tokens: unknown[]; providerTokens: Record<string, string> };
      expect(data.tokens).toBeDefined();
      expect(data.providerTokens).toBeDefined();
    });

    it("allows POST /api/settings/tokens to create tokens when authenticated via Bearer token", async () => {
      const req = new Request("https://spike.land/api/settings/tokens", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${ADMIN_DEFAULT_API_TOKEN}`,
        },
        body: JSON.stringify({
          action: "create_token",
          name: "Subagent Bearer Key",
          customTokenValue: "spk_live_subagent_token_888",
        }),
      });

      const res = await postTokens(req);
      expect(res.status).toBe(201);
      const data = (await res.json()) as { success: boolean; token: { tokenValue: string } };
      expect(data.success).toBe(true);
      expect(data.token.tokenValue).toBe("spk_live_subagent_token_888");

      // Now verify that this newly created token can immediately authenticate API calls!
      const verifyReq = new Request("https://spike.land/api/settings/tokens", {
        headers: { Authorization: "Bearer spk_live_subagent_token_888" },
      });
      const verifyRes = await getTokens(verifyReq);
      expect(verifyRes.status).toBe(200);
    });

    it("allows POST /api/settings/password with Bearer token configured in settings", async () => {
      const req = new Request("https://spike.land/api/settings/password", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${ADMIN_DEFAULT_API_TOKEN}`,
        },
        body: JSON.stringify({
          currentPassword: "admin",
          newPassword: "bearerUpdatedPass2026",
          confirmPassword: "bearerUpdatedPass2026",
        }),
      });

      const res = await changePasswordPost(req);
      expect(res.status).toBe(200);
      const data = (await res.json()) as { success: boolean };
      expect(data.success).toBe(true);
    });

    it("rejects /api/settings/tokens and /api/settings/password with 401 when invalid Bearer token is sent", async () => {
      const badTokensReq = new Request("https://spike.land/api/settings/tokens", {
        headers: { Authorization: "Bearer spk_live_bad_token_999" },
      });
      const tokensRes = await getTokens(badTokensReq);
      expect(tokensRes.status).toBe(401);

      const badPwdReq = new Request("https://spike.land/api/settings/password", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: "Bearer spk_live_bad_token_999",
        },
        body: JSON.stringify({
          currentPassword: "admin",
          newPassword: "newpassword",
        }),
      });
      const pwdRes = await changePasswordPost(badPwdReq);
      expect(pwdRes.status).toBe(401);
    });
  });

  describe("Protected /api/auth/session endpoint", () => {
    it("returns authenticated: true and user profile when Bearer token is provided", async () => {
      const req = new Request("https://spike.land/api/auth/session", {
        headers: { Authorization: `Bearer ${ADMIN_DEFAULT_API_TOKEN}` },
      });

      const res = await getSession(req);
      expect(res.status).toBe(200);
      const data = (await res.json()) as { authenticated: boolean; user: { email: string } };
      expect(data.authenticated).toBe(true);
      expect(data.user.email).toBe("admin@spike.land");
    });

    it("returns authenticated: false when an invalid Bearer token is provided", async () => {
      const req = new Request("https://spike.land/api/auth/session", {
        headers: { Authorization: "Bearer spk_live_fake" },
      });

      const res = await getSession(req);
      expect(res.status).toBe(200);
      const data = (await res.json()) as { authenticated: boolean; user: null };
      expect(data.authenticated).toBe(false);
      expect(data.user).toBeNull();
    });
  });

  describe("Protected /api/hello endpoint", () => {
    it("authenticates and returns user details when valid Bearer token is supplied", async () => {
      const req = new Request("https://spike.land/api/hello", {
        headers: { Authorization: `Bearer ${ADMIN_DEFAULT_API_TOKEN}` },
      });

      const res = await getHello(req);
      expect(res.status).toBe(200);
      const data = (await res.json()) as { message: string; authenticated: boolean; user: { email: string } };
      expect(data.authenticated).toBe(true);
      expect(data.user.email).toBe("admin@spike.land");
    });

    it("rejects requests with invalid Bearer token with 401 Unauthorized", async () => {
      const req = new Request("https://spike.land/api/hello", {
        headers: { Authorization: "Bearer spk_live_invalid_hello_token" },
      });

      const res = await getHello(req);
      expect(res.status).toBe(401);
      const data = (await res.json()) as { error: string };
      expect(data.error).toBe("unauthorized");
    });
  });

  describe("Protected /api/mcp and Virtual Gateway endpoints", () => {
    it("authenticates /api/mcp with Bearer token configured in settings and binds subject", async () => {
      const req = new Request("https://spike.land/api/mcp", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${ADMIN_DEFAULT_API_TOKEN}`,
        },
        body: JSON.stringify({
          jsonrpc: "2.0",
          id: 101,
          method: "tools/call",
          params: {
            name: "list_capability_categories",
            arguments: {},
          },
        }),
      });

      const res = await mcpPost(req);
      expect(res.status).toBe(200);
      const data = (await res.json()) as { result: { content: Array<{ text: string }> } };
      expect(data.result).toBeDefined();
    });

    it("rejects /api/mcp with 401 and JSON-RPC -32001 error when invalid Bearer token is supplied", async () => {
      const req = new Request("https://spike.land/api/mcp", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: "Bearer spk_live_invalid_mcp_bearer",
        },
        body: JSON.stringify({
          jsonrpc: "2.0",
          id: 102,
          method: "tools/call",
          params: {
            name: "list_capability_categories",
            arguments: {},
          },
        }),
      });

      const res = await mcpPost(req);
      expect(res.status).toBe(401);
      const data = (await res.json()) as { error: { code: number; message: string } };
      expect(data.error.code).toBe(-32001);
      expect(data.error.message).toContain("Unauthorized");
    });

    it("rejects Virtual Gateway POST with 401 when invalid Bearer token is supplied", async () => {
      const req = new Request("https://spike.land/api/mcp/g/development", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: "Bearer spk_live_invalid_gateway_key",
        },
        body: JSON.stringify({
          jsonrpc: "2.0",
          id: 103,
          method: "tools/list",
          params: {},
        }),
      });

      const res = await virtualGatewayPost(req, {
        params: Promise.resolve({ gatewaySlug: "development" }),
      });
      expect(res.status).toBe(401);
    });

    it("rejects /api/mcp/sse POST with 401 when invalid Bearer token is supplied", async () => {
      const req = new Request("https://spike.land/api/mcp/sse", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: "Bearer spk_live_invalid_sse_token",
        },
        body: JSON.stringify({
          jsonrpc: "2.0",
          id: 104,
          method: "tools/list",
          params: {},
        }),
      });

      const res = await ssePost(req);
      expect(res.status).toBe(401);
    });
  });

  describe("lib/auth/client-token: client token manager and authenticatedFetch", () => {
    it("stores and retrieves client Bearer token and attaches to fetch requests", async () => {
      expect(getClientBearerToken()).toBeNull();

      setClientBearerToken("spk_live_client_stored_key_777");
      expect(getClientBearerToken()).toBe("spk_live_client_stored_key_777");

      // Verify authenticatedFetch automatically attaches Authorization: Bearer ...
      let passedHeaders: Headers | null = null;
      const originalFetch = globalThis.fetch;
      globalThis.fetch = async (_input, init) => {
        passedHeaders = new Headers(init?.headers);
        return new Response(JSON.stringify({ ok: true }), { status: 200 });
      };

      try {
        await authenticatedFetch("/api/hello");
        expect(passedHeaders?.get("Authorization")).toBe("Bearer spk_live_client_stored_key_777");

        clearClientBearerToken();
        expect(getClientBearerToken()).toBeNull();

        await authenticatedFetch("/api/hello");
        expect(passedHeaders?.get("Authorization")).toBeNull();
      } finally {
        globalThis.fetch = originalFetch;
      }
    });
  });
});
